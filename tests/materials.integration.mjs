async function req(i, path, body, method, headers = {}) {
  const r = await fetch(origin + path, {
    method: method || (body === undefined ? "GET" : "POST"),
    headers: {
      Origin: origin,
      ...(i === null ? {} : { Cookie: `radar_session=${users[i].token}` }),
      ...(body === undefined ? {} : { "Content-Type": "application/json" }),
      ...headers,
    },
    ...(body === undefined
      ? {}
      : {
          body:
            typeof body === "object" && !(body instanceof Uint8Array)
              ? JSON.stringify(body)
              : body,
        }),
  });
  const type = r.headers.get("content-type") || "";
  return {
    status: r.status,
    headers: r.headers,
    data:
      method === "HEAD"
        ? null
        : type.includes("json")
          ? await r.json()
          : new Uint8Array(await r.arrayBuffer()),
  };
}
