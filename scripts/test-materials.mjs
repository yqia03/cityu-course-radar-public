import {
  mkdtemp,
  mkdir,
  rm,
  open,
  readFile,
  writeFile,
} from "node:fs/promises";
import { spawn, execFileSync } from "node:child_process";
import { resolve } from "node:path";
import { createHash, randomUUID } from "node:crypto";
import assert from "node:assert/strict";
await mkdir(".sites-runtime/evidence", { recursive: true });
const state = await mkdtemp(resolve(".sites-runtime/materials-state-"));
const log = await open(".sites-runtime/evidence/materials-server.log", "w");
const env = {
  ...process.env,
  RADAR_TEST_STATE: state,
  TEST_ORIGIN: "http://localhost:5174",
  TEST_RESTART: "1",
};
let server;
async function stop() {
  if (server && server.exitCode === null && server.signalCode === null) {
    const stopped = new Promise((r) => server.once("exit", r));
    server.kill("SIGTERM");
    await stopped;
  }
}
async function start() {
  server = spawn(
    process.execPath,
    ["scripts/run-framework.mjs", "dev", "--port", "5174"],
    { env, stdio: ["ignore", log.fd, log.fd] },
  );
  for (let i = 0; i < 90; i++) {
    if (server.exitCode !== null) break;
    try {
      if ((await fetch(env.TEST_ORIGIN + "/api/session")).ok) return;
    } catch {}
    await new Promise((r) => setTimeout(r, 500));
  }
  throw new Error("Material test server did not start; see local evidence log");
}
async function requestAs(token, path, body, method) {
  return fetch(env.TEST_ORIGIN + path, {
    method: method || (body === undefined ? "GET" : "POST"),
    headers: {
      Origin: env.TEST_ORIGIN,
      ...(token ? { Cookie: `radar_session=${token}` } : {}),
      ...(body === undefined
        ? {}
        : {
            "Content-Type":
              body instanceof Uint8Array
                ? "application/pdf"
                : "application/json",
          }),
    },
    ...(body === undefined
      ? {}
      : { body: body instanceof Uint8Array ? body : JSON.stringify(body) }),
  });
}
async function checkUploadModes(fixture) {
  const checks = [];
  const check = (condition, label) => {
    assert.ok(condition, label);
    console.log("PASS", label);
    checks.push(label);
  };
  const course =
    "ZZMODE" +
    String(Date.now()).slice(-4) +
    randomUUID().slice(0, 3).toUpperCase();
  // Reuse the real PDF generated by the isolated suite and add a PDF comment,
  // retaining valid object offsets while giving this fixture a distinct digest.
  const original = await readFile(".sites-runtime/self-authored-test.pdf"),
    eof = original.lastIndexOf("%%EOF"),
    bytes = Buffer.concat([
      original.subarray(0, eof),
      Buffer.from(`% Upload-mode fixture ${course}\n`),
      original.subarray(eof),
    ]);
  const declaration = {
    courseCode: course,
    title: "Disposable upload mode validation",
    category: "notes",
    academicYear: "2025/2026",
    semester: "A",
    rightsBasis: "own",
    rightsDeclaration:
      "This self-authored PDF exists only in the isolated local test state.",
    size: bytes.length,
    sha256: createHash("sha256").update(bytes).digest("hex"),
  };
  let adminUpload;
  for (const mode of ["admin-only", "unknown-mode"]) {
    await stop();
    env.RADAR_TEST_UPLOAD_MODE = mode;
    await start();
    let cursor;
    do {
      const response = await requestAs(
        fixture.adminToken,
        "/api/admin/materials/operations",
        {
          action: "reconcile",
          ...(cursor ? { cursor } : {}),
          reason: "Complete isolated upload mode validation reconciliation",
        },
      );
      assert.equal(response.status, 200);
      cursor = (await response.json()).nextCursor;
    } while (cursor);
    assert.equal(
      (
        await requestAs(fixture.adminToken, "/api/admin/materials/operations", {
          action: "settings",
          uploadsEnabled: true,
          capacityBytes: 80000000,
          reason:
            "Enable bounded uploads while independently enforcing access mode",
        })
      ).status,
      200,
    );
    if (mode === "admin-only") {
      assert.equal(
        (
          await requestAs(fixture.adminToken, "/api/courses", {
            code: course,
            titleEn: "Disposable upload mode validation",
            titleZhHans: "上传模式测试",
            titleZhHant: "上傳模式測試",
            descriptionEn:
              "Self-authored local fixture for upload admission checks.",
            descriptionZhHans: "仅用于隔离本地测试，不是实际课程。",
            descriptionZhHant: "僅用於隔離本地測試，不是實際課程。",
            department: "Test",
            credits: "3",
            level: "ug",
            sourceUrl: "https://www.cityu.edu.hk/catalogue/",
          })
        ).status,
        201,
      );
    }
    for (const [label, token] of [
      ["anonymous", null],
      ["ordinary", fixture.token],
      ["admin", fixture.adminToken],
    ]) {
      const response = await requestAs(
        token,
        `/api/courses/${course}/materials`,
      );
      const catalogue = await response.json();
      check(
        response.status === 200 &&
          catalogue.uploadsEnabled ===
            (mode === "admin-only" && label === "admin"),
        `${mode} catalogue reports effective upload access for ${label}`,
      );
    }
    check(
      (await requestAs(fixture.token, "/api/materials/uploads", declaration))
        .status === 503,
      `${mode} blocks ordinary upload reservations`,
    );
    check(
      (
        await requestAs(
          fixture.token,
          `/api/materials/uploads/${fixture.uploadId}`,
          bytes,
          "PUT",
        )
      ).status === 503,
      `${mode} blocks ordinary upload bytes independently of reservation state`,
    );
    const ownerDownload = await requestAs(
      fixture.token,
      `/api/materials/${fixture.materialId}/download`,
    );
    check(
      ownerDownload.status === 200,
      `${mode} preserves authorized downloads`,
    );
    await ownerDownload.body?.cancel();
    const reservation = await requestAs(
      fixture.adminToken,
      "/api/materials/uploads",
      declaration,
    );
    if (mode === "admin-only") {
      check(
        reservation.status === 201,
        "admin-only admits a real admin session reservation",
      );
      adminUpload = await reservation.json();
      check(
        (
          await requestAs(
            fixture.adminToken,
            adminUpload.uploadUrl,
            bytes,
            "PUT",
          )
        ).status === 200,
        "admin-only streams and verifies the administrator PDF in R2",
      );
      check(
        (
          await requestAs(
            fixture.adminToken,
            adminUpload.uploadUrl,
            bytes,
            "PUT",
          )
        ).status === 409,
        "admin-only retains immutable upload replay protection",
      );
      check(
        (
          await requestAs(fixture.adminToken, "/api/materials/uploads", {
            ...declaration,
            size: 50000001,
          })
        ).status === 400,
        "admin-only retains the server file size bound",
      );
    } else {
      check(
        reservation.status === 503,
        "unknown upload mode blocks admin reservations",
      );
      check(
        (
          await requestAs(
            fixture.adminToken,
            adminUpload.uploadUrl,
            bytes,
            "PUT",
          )
        ).status === 503,
        "unknown upload mode also blocks admin upload bytes",
      );
    }
  }
  await writeFile(
    ".sites-runtime/evidence/material-upload-modes.json",
    JSON.stringify({ checks: checks.length, passed: checks }, null, 2),
  );
}
try {
  execFileSync(
    process.execPath,
    [
      "./node_modules/wrangler/bin/wrangler.js",
      "d1",
      "migrations",
      "apply",
      "DB",
      "--local",
      "--config",
      "wrangler.json",
      "--persist-to",
      state,
    ],
    { stdio: "pipe", env },
  );
  await start();
  const status = await new Promise((res, rej) => {
    const child = spawn(process.execPath, ["tests/materials.integration.mjs"], {
      env,
      stdio: "inherit",
    });
    child.on("exit", res);
    child.on("error", rej);
  });
  if (status !== 0) process.exitCode = 1;
  else {
    await stop();
    await start();
    const fixture = JSON.parse(
      await readFile(".sites-runtime/material-persistence.json", "utf8"),
    );
    const headers = { Cookie: `radar_session=${fixture.token}` };
    const response = await fetch(
      env.TEST_ORIGIN + `/api/materials/${fixture.materialId}/download`,
      { headers },
    );
    assert.equal(response.status, 200);
    assert.equal(
      createHash("sha256")
        .update(new Uint8Array(await response.arrayBuffer()))
        .digest("hex"),
      fixture.sha256,
    );
    console.log(
      "PASS object and owner permission persist after complete Worker restart",
    );
    const points = await (
      await fetch(env.TEST_ORIGIN + "/api/points", { headers })
    ).json();
    assert.equal(points.balance, 53);
    assert.equal(
      points.ledger.filter((x) => x.kind === "upload_reward").length,
      2,
    );
    assert.equal(
      points.ledger.filter((x) => x.kind === "upload_revoke").length,
      1,
    );
    console.log(
      "PASS ledger, reward reversal and balance independently persist after restart",
    );
    await writeFile(
      ".sites-runtime/evidence/materials-restart.json",
      JSON.stringify(
        { checks: 2, objectAndOwnerPermission: true, ledgerAndBalance: true },
        null,
        2,
      ),
    );
    await checkUploadModes(fixture);
  }
} finally {
  await stop();
  await log.close();
  await rm(state, { recursive: true, force: true });
  await rm(".sites-runtime/material-persistence.json", { force: true });
}
