import { readFile, writeFile } from "node:fs/promises";
import { gzipSync } from "node:zlib";
const source = JSON.parse(
  await readFile(new URL("../data/courses.json", import.meta.url), "utf8"),
);
const packed = gzipSync(JSON.stringify(source), { level: 9 }).toString(
  "base64",
);
await writeFile(
  new URL("../data/catalogue.generated.ts", import.meta.url),
  `// Generated by scripts/pack-catalogue.mjs. Do not edit.\nexport default ${JSON.stringify(packed)};\n`,
);
console.log(
  `Packed ${source.length} courses into ${(packed.length / 1024 / 1024).toFixed(2)} MiB.`,
);
